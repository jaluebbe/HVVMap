"""Derive the line list (mode, color) from GTFS routes.txt."""

import argparse
import csv
from dataclasses import dataclass

FERRY_AGENCY = "73"  # HADAG harbor ferries; agency_name is useless in this feed
BLACK = "000000"
WHITE = "FFFFFF"


@dataclass(frozen=True)
class Line:
    name: str
    mode: str
    color: str
    route_ids: tuple[str, ...]


def classify(route_type: str, agency_id: str, name: str) -> str | None:
    """Map GTFS route_type (+ agency/name hints) to a mode, None if ignored."""
    if route_type == "402":
        return "U"
    if route_type == "109":
        return "S"
    if route_type == "1200":
        return "FERRY" if agency_id == FERRY_AGENCY else None
    if route_type == "2":
        return "AKN" if name.startswith("A") else "REGIO"  # RE and RB
    if route_type in ("3", "702"):
        return "BUS"
    return None


def derive_color(color: str, text_color: str, mode: str) -> str:
    """route_color unless unusable (white/empty), else route_text_color."""
    color, text_color = color.strip(), text_color.strip()
    if color and color.upper() != WHITE:
        return color
    if text_color and text_color.upper() != WHITE:
        return text_color
    return BLACK if mode == "REGIO" else ""


def load_lines(routes_path: str) -> list[Line]:
    """Read routes.txt and merge duplicate entries per (mode, name)."""
    merged: dict[tuple[str, str], dict] = {}
    with open(routes_path, encoding="utf-8-sig", newline="") as f:
        for r in csv.DictReader(f):
            name = r["route_short_name"]
            mode = classify(r["route_type"], r["agency_id"], name)
            if mode is None:
                continue
            color = derive_color(r["route_color"], r["route_text_color"], mode)
            entry = merged.setdefault((mode, name), {"color": "", "ids": []})
            entry["color"] = entry["color"] or color
            entry["ids"].append(r["route_id"])
    return [
        Line(name, mode, e["color"], tuple(e["ids"]))
        for (mode, name), e in sorted(merged.items())
    ]


def select(
    lines: list[Line],
    modes: set[str] | None = None,
    names: set[str] | None = None,
) -> list[Line]:
    """Filter by mode and/or explicit line names."""
    return [
        ln
        for ln in lines
        if (modes is None or ln.mode in modes) and (names is None or ln.name in names)
    ]


def write_colors_module(lines: list[Line], out_path: str) -> None:
    """Write a Python module with {name: (mode, color)} for lines.py."""
    rows = [f'    "{ln.name}": ("{ln.mode}", "{ln.color}"),' for ln in lines]
    header = (
        '"""Line modes and colors derived from GTFS routes.txt.\n\n'
        "Generated by hvv_map.gtfs_lines (--write-colors), do not edit.\n"
        '"""\n\n'
    )
    body = "GTFS_LINES: dict[str, tuple[str, str]] = {\n"
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(header + body + "\n".join(rows) + "\n}\n")


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("routes_txt")
    p.add_argument("--modes", default="U,S,AKN,REGIO,FERRY")
    p.add_argument("--names", default="")
    p.add_argument("--write-colors", metavar="PATH")
    a = p.parse_args()
    names = set(a.names.split(",")) if a.names else None
    chosen = select(load_lines(a.routes_txt), set(a.modes.split(",")), names)
    if a.write_colors:
        write_colors_module(chosen, a.write_colors)
        print(f"wrote {len(chosen)} lines to {a.write_colors}")
        return
    for ln in chosen:
        print(
            f"{ln.mode:6} {ln.name:6} #{ln.color or '------':6} "
            f"{len(ln.route_ids)} route_id(s)"
        )


if __name__ == "__main__":
    main()
